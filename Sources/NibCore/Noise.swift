import Foundation

/// Changes that cost a lot of tokens and say little about intent. They show up in the
/// file list, but their content never reaches the model.
public enum NoiseKind: String, Sendable, Equatable {
    case binary
    case lockfile
    case generated
    case minified
    case vendored
    case xcodeProject = "xcode project"
    case snapshot
}

public enum NoiseFilter {
    static let lockfiles: Set<String> = [
        "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb",
        "Package.resolved", "Podfile.lock", "Cartfile.resolved", "Cargo.lock", "Gemfile.lock",
        "poetry.lock", "Pipfile.lock", "uv.lock", "composer.lock", "go.sum", "mix.lock",
        "pubspec.lock", "flake.lock", "packages.lock.json", "gradle.lockfile",
    ]
    /// Directories that are vendored or generated wherever they appear.
    static let vendoredAnywhere: Set<String> = [
        "node_modules", ".build", "DerivedData", "Pods", "Carthage", ".next", ".nuxt", "__pycache__", ".venv",
    ]
    /// Directories that are build output when they sit at the top of the repo.
    static let generatedAtRoot: Set<String> = ["dist", "build", "out", "coverage", "vendor"]

    public static func classify(_ file: FileDiff) -> NoiseKind? {
        if file.isBinary { return .binary }

        let path = file.path
        let components = path.split(separator: "/").map(String.init)
        let name = components.last ?? path
        let lower = name.lowercased()

        if lockfiles.contains(name) { return .lockfile }
        if components.dropLast().contains(where: { vendoredAnywhere.contains($0) }) { return .vendored }
        if let root = components.first, components.count > 1, generatedAtRoot.contains(root) { return .generated }
        if lower.hasSuffix(".min.js") || lower.hasSuffix(".min.css") || lower.hasSuffix(".map") { return .minified }
        if lower.hasSuffix(".pbxproj") || lower.hasSuffix(".xcworkspacedata") || components.contains(where: { $0.hasSuffix("xcuserdata") }) {
            return .xcodeProject
        }
        if components.contains("__snapshots__") || lower.hasSuffix(".snap") { return .snapshot }
        if hasGeneratedMarker(file) { return .generated }
        return nil
    }

    /// Looks for "@generated" / "DO NOT EDIT" in the first lines of a file, where generators put it.
    /// Only for hunks that start at the top, so a mention further down (in a test, say) doesn't count.
    static func hasGeneratedMarker(_ file: FileDiff) -> Bool {
        guard let first = file.hunks.first, first.hasPrefix("@@ -0,") || first.hasPrefix("@@ -1,") || first.hasPrefix("@@ -1 ")
        else { return false }
        let head = first.split(separator: "\n").dropFirst().prefix(5)
        return head.contains { line in
            line.contains("@generated") || line.contains("DO NOT EDIT") || line.contains("Code generated by")
        }
    }
}
