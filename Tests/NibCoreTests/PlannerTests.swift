import Testing
@testable import NibCore

@Suite("Noise filter")
struct NoiseFilterTests {
    @Test(arguments: [
        ("package-lock.json", NoiseKind.lockfile),
        ("ios/Podfile.lock", .lockfile),
        ("App.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved", .lockfile),
        ("web/node_modules/left-pad/index.js", .vendored),
        ("dist/app.js", .generated),
        ("public/app.min.js", .minified),
        ("App.xcodeproj/project.pbxproj", .xcodeProject),
        ("src/__snapshots__/view.test.ts.snap", .snapshot),
    ])
    func classifiesNoise(path: String, kind: NoiseKind) {
        let file = Fixture.files(Fixture.modified(path))[0]
        #expect(NoiseFilter.classify(file) == kind)
    }

    @Test func leavesSourceAlone() {
        for path in ["Sources/App.swift", "src/build/compiler.ts", "README.md"] {
            #expect(NoiseFilter.classify(Fixture.files(Fixture.modified(path))[0]) == nil)
        }
    }

    @Test func markerFurtherDownDoesNotCount() {
        let lines = (0..<20).map { "let x\($0) = \($0)" } + ["// DO NOT EDIT is just a phrase here"]
        let file = Fixture.files(Fixture.added("Tests/MarkerTests.swift", lines: lines))[0]
        #expect(NoiseFilter.classify(file) == nil)
    }

    @Test func spotsGeneratedMarker() {
        let file = Fixture.files(Fixture.added("api/client.go", lines: ["// Code generated by protoc. DO NOT EDIT.", "package api"]))[0]
        #expect(NoiseFilter.classify(file) == .generated)
    }
}

@Suite("Planner")
struct PlannerTests {
    @Test func smallDiffIsOnePass() {
        let files = Fixture.files(Fixture.modified("A.swift"), Fixture.modified("B.swift"))
        let plan = Planner.plan(files, budgetChars: 5_000)
        #expect(plan.mode == .single)
        #expect(plan.chunks.count == 1)
        #expect(plan.chunks[0].contains("### A.swift"))
        #expect(plan.chunks[0].contains("### B.swift"))
    }

    @Test func noiseNeverReachesTheModel() {
        let lock = Fixture.added("package-lock.json", lines: Array(repeating: "\"x\": 1,", count: 500))
        let files = Fixture.files(Fixture.modified("index.js"), lock)
        let plan = Planner.plan(files, budgetChars: 2_000)
        #expect(plan.mode == .single)
        #expect(!plan.chunks[0].contains("package-lock.json"))
        #expect(plan.overview.contains("package-lock.json"))
        #expect(plan.noise == [NoisyFile(path: "package-lock.json", kind: .lockfile)])
    }

    @Test func deletedFileContentIsNotSent() {
        let files = Fixture.files(Fixture.deleted("Legacy.swift", lines: 300))
        let plan = Planner.plan(files, budgetChars: 2_000)
        #expect(plan.mode == .single)
        #expect(!plan.chunks[0].contains("line 12"))
        #expect(plan.chunks[0].contains("deleted"))
    }

    @Test func bigDiffIsSplitAndEveryChunkFits() {
        let files = Fixture.files(
            Fixture.big("Engine.swift", hunks: 12, linesPerHunk: 20),
            Fixture.big("Renderer.swift", hunks: 6, linesPerHunk: 20),
            Fixture.modified("README.md")
        )
        let budget = 3_000
        let plan = Planner.plan(files, budgetChars: budget)
        #expect(plan.mode == .mapReduce)
        #expect(plan.chunks.count > 1)
        for chunk in plan.chunks { #expect(chunk.count <= budget) }
        let everything = plan.chunks.joined()
        #expect(everything.contains("Engine.swift"))
        #expect(everything.contains("Renderer.swift"))
        #expect(everything.contains("README.md"))
        #expect(everything.contains("part 1/"))
    }

    @Test func hugeSingleHunkIsTruncated() {
        let files = Fixture.files(Fixture.big("Generated.swift", hunks: 1, linesPerHunk: 2_000))
        let plan = Planner.plan(files, budgetChars: 3_000)
        #expect(plan.chunks.allSatisfy { $0.count <= 3_000 })
        #expect(plan.chunks.joined().contains("lines omitted"))
    }

    @Test func chunkCapKeepsTheBiggestChangesAndFillsGaps() {
        let files = Fixture.files(
            Fixture.big("Core.swift", hunks: 4, linesPerHunk: 30),
            Fixture.big("Other.swift", hunks: 4, linesPerHunk: 30),
            Fixture.modified("Tiny.swift")
        )
        let plan = Planner.plan(files, budgetChars: 1_500, maxChunks: 2)
        #expect(plan.chunks.count == 2)
        #expect(plan.omitted == ["Core.swift", "Other.swift"])   // Core only partly
        #expect(plan.chunks.joined().contains("### Core.swift"))
        #expect(plan.chunks.joined().contains("### Tiny.swift"))   // small enough to share a chunk
    }

    @Test func bigNewFileIsSentAsAnOutline() {
        var lines = ["import Foundation", "", "/// Parses diffs.", "/// Second doc line.", "public enum DiffParser {"]
        lines += (0..<60).map { "    let value\($0) = \($0)" }
        lines += ["    @discardableResult public static func parse(_ raw: String) -> [FileDiff] {", "    }", "}"]
        let file = Fixture.files(Fixture.added("Sources/Diff.swift", lines: lines))[0]
        let text = Planner.render(file)
        #expect(text.contains("outline"))
        #expect(text.contains("public enum DiffParser {"))
        #expect(text.contains("public static func parse"))
        #expect(text.contains("/// Parses diffs."))
        #expect(!text.contains("Second doc line"))
        #expect(!text.contains("let value"))
    }

    @Test func smallNewFileIsSentInFull() {
        let file = Fixture.files(Fixture.added("Sources/Tiny.swift", lines: ["let a = 1", "let b = 2"]))[0]
        #expect(Planner.render(file).contains("+let b = 2"))
    }

    @Test func markdownOutlineKeepsHeadings() {
        let lines = ["# nib", "intro"] + (0..<50).map { "text \($0)" } + ["## Install", "more"]
        let file = Fixture.files(Fixture.added("README.md", lines: lines))[0]
        let text = Planner.render(file)
        #expect(text.contains("# nib"))
        #expect(text.contains("## Install"))
        #expect(!text.contains("text 3"))
    }

    @Test func truncateKeepsHeadAndTail() {
        let text = (0..<500).map { "line \($0)" }.joined(separator: "\n")
        let short = Planner.truncate(text, to: 400)
        #expect(short.count <= 400)
        #expect(short.hasPrefix("line 0"))
        #expect(short.hasSuffix("line 499"))
        #expect(short.contains("lines omitted"))
    }

    @Test func overviewIsCapped() {
        let diffs = (0..<200).map { Fixture.modified("File\($0).swift") }
        let files = DiffParser.parse(diffs.joined(separator: "\n"))
        let overview = Planner.overview(files, maxChars: 500)
        #expect(overview.count < 600)
        #expect(overview.contains("more files"))
    }
}
